// contrastFacts: [{ text, ratio, heightPx }, ...] — 클라이언트가 브라우저
// 캔버스에서 OCR 텍스트 영역의 실제 픽셀을 읽어 Otsu 이진화로 글자/배경을
// 분리한 뒤 WCAG 명도 대비 공식으로 계산한 값. heightPx는 OCR 박스 높이를
// 원본 이미지 기준 px로 환산한 값으로, 폰트 크기의 근사치다. 서버는 이
// 숫자를 그대로 프롬프트에 "사실"로 주입만 하고, 계산 자체는 하지 않는다
// (이미지 디코딩 라이브러리가 없어도 되도록 클라이언트에서 처리).
//
// WCAG는 큰 텍스트(18pt/24px 이상, 또는 14pt 굵게/약 18.7px 이상)에는
// 4.5:1 대신 완화된 3:1 기준을 허용한다(KWCAG 2.2 동일). OCR로는 굵기까지
// 구분할 수 없어 24px 단일 기준으로 단순화했다 — 실제로는 18.7px대의 굵은
// 텍스트가 "미달"로 표시될 수 있으니 이 프롬프트에서도 그 여지를 안내한다.
function formatContrastForPrompt(contrastFacts) {
  const lines = contrastFacts.map((f) => {
    const isLarge = Number.isFinite(f.heightPx) && f.heightPx >= 24;
    const threshold = isLarge ? 3 : 4.5;
    const flag = Number.isFinite(f.ratio) && f.ratio < threshold ? ` — WCAG 참고 기준(${threshold}:1)보다 낮음` : '';
    const sizeNote = isLarge ? ' [큰 텍스트로 추정, 완화 기준 3:1 적용]' : '';
    return `"${f.text}" — 추정 명도 대비 약 ${f.ratio}:1${flag}${sizeNote}`;
  });
  return `\n\n브라우저에서 직접 측정한 텍스트별 명도 대비 (텍스트 영역 안의 밝기 분포를 이진화해서 계산한 근사치입니다 — 정확한 픽셀 단위는 아니지만 시각적 추측보다 신뢰할 수 있습니다):
${lines.join('\n')}

3번(타이포·정렬·여백·명도대비)의 텍스트-배경 대비를 판정할 때 이 수치를 참고하세요 — 법적 의무 기준이 아니라 "많은 사람이 편하게 읽을 수 있는 대비"를 가늠하는 접근성 참고 수치입니다. 일반 텍스트는 4.5:1보다 낮으면 WCAG 참고 기준상 가독성이 부족한 것으로 보고, [큰 텍스트로 추정] 표시가 붙은 항목은 3:1보다 낮을 때만 참고 기준에 못 미치는 것으로 보세요 — 헤드라인처럼 큰 텍스트는 WCAG상 원래 더 낮은 대비도 허용됩니다. 어느 쪽이든 기준선에 근소하게 못 미치는 수준(예: 일반 텍스트 3.5~4.5, 큰 텍스트 2.5~3 사이)이면 곧바로 needsfix로 올리지 말고 실제로 눈으로 봤을 때도 읽기 불편한지 시각적으로 한 번 더 확인해서 판단하세요. 뚜렷하게 참고 기준에 못 미치는 경우만 needsfix 이상으로 판정하세요.

단, 위 수치가 참고 기준에 못 미치는 텍스트가 쿠폰 유효기간·사용조건·제외상품 안내, 법적고지·지급조건·면책사항 같은 부가조건·고지성 텍스트라면(텍스트 내용을 보고 판단) needsfix로 올리지 마세요 — 이런 텍스트는 핵심 카피보다 낮은 대비로 처리하는 게 정상적인 위계 표현입니다. 이 수치 기반 완화는 헤드라인·할인율·금액·CTA 같은 핵심 카피에는 적용하지 마세요.

이 수치를 근거로 지적할 때는 note에 "묻힘"·"안 보임"처럼 육안으로 봐도 명백히 안 보인다는 식으로 쓰지 마세요 — 실제로는 눈에 잘 보이는데 측정치만 참고 기준에 못 미치는 경우도 많습니다(그라데이션 배경처럼 측정이 어려운 경우 특히 그렇습니다). "미달"·"탈락"처럼 불합격 판정처럼 들리는 단정적인 단어도 쓰지 마세요 — 이건 법적 의무 기준이 아니라 접근성 참고 수치입니다. 대신 "WCAG 참고 기준 대비 OO:1로 낮음(기준 X:1)"처럼, 담담하게 수치를 전달하는 식으로 표현하세요.`;
}

// 브랜드 가이드 텍스트(customFields가 "- 라벨: 값" 줄로 합쳐진 것 포함)에서
// HEX/RGB 색상 코드를 정규식으로 뽑아낸다. 별도 구조화 입력 필드 없이도
// 지금 팀이 쓰는 자유 텍스트 표기 그대로 동작하도록 세 가지 패턴을 모두
// 지원한다: "#FF2e98" 같은 HEX, "rgb(255,46,152)" 같은 표기, 그리고
// 괄호 없이 "255, 46, 152"처럼 숫자만 적는 표기(팀이 실제로 이 방식을
// 쓴다고 확인됨).
function extractBrandColors(guidelineText) {
  if (!guidelineText) return [];
  const colors = [];
  const hexRe = /#([0-9A-Fa-f]{6}|[0-9A-Fa-f]{3})\b/g;
  let m;
  while ((m = hexRe.exec(guidelineText))) {
    let hex = m[1];
    if (hex.length === 3) hex = hex.split('').map((c) => c + c).join('');
    colors.push({
      hex: '#' + hex.toUpperCase(),
      r: parseInt(hex.slice(0, 2), 16),
      g: parseInt(hex.slice(2, 4), 16),
      b: parseInt(hex.slice(4, 6), 16),
    });
  }
  // rgb(...) 래핑 여부와 무관하게 "숫자,숫자,숫자" 형태를 전부 잡는다
  // (rgb(255,46,152)의 안쪽 숫자도 이 패턴으로 같이 잡히므로 아래에서
  // hex 기준으로 중복 제거한다).
  const tripletRe = /(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})/g;
  while ((m = tripletRe.exec(guidelineText))) {
    const r = Number(m[1]), g = Number(m[2]), b = Number(m[3]);
    if (r <= 255 && g <= 255 && b <= 255) {
      colors.push({ hex: '#' + [r, g, b].map((v) => v.toString(16).padStart(2, '0')).join('').toUpperCase(), r, g, b });
    }
  }
  const seen = new Set();
  return colors.filter((c) => (seen.has(c.hex) ? false : (seen.add(c.hex), true)));
}

// "redmean" 색상 거리 근사식 — 사람 눈의 색상 인지에 맞춰 채널별 가중치를
// 조정한 저비용 근사치다(완전한 CIE ΔE2000 같은 과학적 표준은 아니고,
// 그보다 훨씬 간단하면서 단순 유클리드 거리보다는 인지적으로 더 정확한
// 실무용 근사식 — https://www.compuphase.com/cmetric.htm). 이 값 자체를
// 절대 기준으로 쓰지 않고, "가깝다/멀다"를 가르는 참고용 임계치로만 쓴다.
function redmeanDistance(c1, c2) {
  const rmean = (c1.r + c2.r) / 2;
  const dr = c1.r - c2.r, dg = c1.g - c2.g, db = c1.b - c2.b;
  return Math.sqrt((2 + rmean / 256) * dr * dr + 4 * dg * dg + (2 + (255 - rmean) / 256) * db * db);
}

// dominantColors: 클라이언트가 이미지를 6x6으로 축소해서 뽑은 36개 칸의
// 평균색 — 정교한 색상 분할이 아니라 "대략 이런 색들이 쓰였다"는 참고용
// 샘플링이다. brandColors: 브랜드 가이드에서 뽑은 HEX/RGB 목록.
function formatColorDistanceForPrompt(dominantColors, brandColors) {
  if (!dominantColors || !dominantColors.length || !brandColors || !brandColors.length) return '';
  const CLOSE_THRESHOLD = 60; // redmean 스케일에서 "육안으로도 비슷한 색"으로 볼 만한 근사 임계치
  let closeCount = 0;
  let minDist = Infinity, minMatch = null;
  for (const c of dominantColors) {
    let best = Infinity, bestHex = null;
    for (const b of brandColors) {
      const d = redmeanDistance(c, b);
      if (d < best) { best = d; bestHex = b.hex; }
    }
    if (best < CLOSE_THRESHOLD) closeCount++;
    if (best < minDist) { minDist = best; minMatch = bestHex; }
  }
  const pct = Math.round((closeCount / dominantColors.length) * 100);
  const brandHexList = brandColors.map((c) => c.hex).join(', ');

  return `\n\n브랜드 컬러 샘플링 결과 (참고용 — 이미지를 6x6 격자로 축소해서 각 칸의 평균색을 브랜드 컬러(${brandHexList})와 비교한 근사치입니다. 정교한 영역 분할이 아니라 대략적인 색 분포 참고용입니다):
- 36개 샘플 중 브랜드 컬러와 육안상 비슷한 색으로 볼 만큼 가까운 샘플: ${closeCount}개 (약 ${pct}%)
- 가장 가까운 샘플과 브랜드 컬러(${minMatch}) 간 거리: 약 ${Math.round(minDist)}

5번(컬러 일관성)을 판정할 때 이 수치를 참고하세요. 이 샘플링은 이미지 전체를 성기게 나눈 것이라 작은 로고·텍스트 색상이나 정교한 영역 구분은 반영하지 못합니다 — "브랜드 컬러가 전혀 안 보인다"는 근거로는 쓰지 말고, 육안으로 직접 확인한 결과와 같이 참고하세요. 근접 비율이 낮게 나와도(예: 10% 미만) 시즌 컨셉 등으로 브랜드 컬러와 다른 계열을 의도적으로 쓴 것으로 보이면 지적하지 마세요 — 이미 안내된 시즌 컨셉 예외를 그대로 적용합니다. 반대로 브랜드 컬러가 이미지 안에 육안으로도 전혀 안 보이는데 샘플링 결과도 근접 비율이 0%에 가깝다면, 이 두 근거를 함께 note에 언급하며 지적할 수 있습니다.`;
}

